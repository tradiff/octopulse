export async function navigation(page, capture) {
  const origin = await page.evaluate(() => location.origin);
  const parameter = (name, all = false) => page.evaluate(({ name, all }) => {
    const query = new URLSearchParams(location.search); return all ? query.getAll(name) : query.get(name);
  }, { name, all });
  let checks = 0;
  const check = (condition, message) => { if (!condition) throw new Error(message); checks++; };
  const ready = () => page.waitForFunction(() => document.querySelector('#status').textContent.includes('refreshed'));
  const go = async path => { await page.goto(origin + path); await ready(); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await go('/');
  check(await page.locator('#identity > span').last().textContent() === '@alex', 'Identity is visible');
  check(await page.getByRole('button', { name: 'Needs My Review (2)', exact: true }).count() === 1, 'Queue counts reflect direct and team requests');
  const summary = page.locator('[data-pr="A"] > summary');
  await summary.focus(); await page.keyboard.press('Enter');
  await page.locator('[data-pr="A"][open]').waitFor();
  await page.getByText('Added the test.', { exact: true }).waitFor();
  check(await page.getByText('Added the test.', { exact: true }).isVisible(), 'Self-suppressed activity remains in timeline');
  check(await page.locator('.timeline .badge').filter({ hasText: /^eligible$/ }).count() === 0, 'Internal eligible badges are hidden');
  check(await page.locator('.timeline .badge').filter({ hasText: /^self$/ }).isVisible(), 'Other activity decision badges remain visible');
  check(await page.getByText('Linux tests: pending', { exact: true }).isVisible(), 'Current-head jobs are visible');
  check((await page.locator('[data-pr="A"] time').first().getAttribute('title')).length > 20, 'Exact localized timestamp is available');
  await capture('navigation-desktop.png');
  await summary.focus(); await page.keyboard.press('Space');
  await page.waitForFunction(() => !document.querySelector('[data-pr="A"]').open);
  check(true, 'Space collapses row');
  const title = page.getByRole('link', { name: 'Make workflow retries reliable', exact: true });
  await title.evaluate(el => el.addEventListener('click', event => event.preventDefault(), { once: true }));
  await title.click();
  check(await page.locator('[data-pr="A"]').getAttribute('open') === null, 'Link click does not expand row');
  await page.getByRole('button', { name: 'Needs My Review (2)', exact: true }).click(); await ready();
  await page.getByRole('combobox', { name: 'Repository', exact: true }).fill('service');
  await page.getByRole('option', { name: 'acme/service', exact: true }).click(); await ready();
  check(await page.locator('.pr').count() === 1, 'Repository filters intersect queue');
  check(await page.getByText('Blocked by rules', { exact: true }).isVisible(), 'Blocked merge label is separate');
  check(await page.getByText('Requested teams: acme/platform', { exact: true }).isVisible(), 'Pending team is separate');
  check((await parameter('pr-state', true)).includes('tracked'), 'Repository change preserves selected tracking filter');
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click(); await ready();
  await page.getByRole('button', { name: 'My PRs (2)', exact: true }).click(); await ready();
  check(await page.getByText('Earlier merged change', { exact: true }).isVisible(), 'Explicit cleared state reveals inactive history');
  await page.reload(); await ready();
  check(await page.getByText('Earlier merged change', { exact: true }).isVisible(), 'Cleared filters survive reload');
  await page.goBack(); await ready();
  check(await parameter('tab') === 'needs-my-review', 'Back restores queue');
  await page.goForward(); await ready();
  check(await parameter('tab') === 'my-prs', 'Forward restores queue');

  await go('/notification-history');
  check(await page.locator('.notification').count() === 50, 'History page size is fifty');
  check(await page.locator('.notification-body').first().isHidden(), 'History content starts collapsed');
  const notificationSummary = page.locator('.notification > summary').first();
  await notificationSummary.focus(); await page.keyboard.press('Enter');
  check(await page.locator('.notification-body').first().isVisible(), 'Keyboard expands saved notification content');
  check(await page.getByText('Service acceptance does not confirm the notification was displayed or read.', { exact: true }).first().isVisible(), 'Transport acceptance is not presented as user acknowledgement');
  check(await page.getByText('Accepted by service', { exact: true }).count() === 0, 'Sent records omit routine delivery labels');
  await page.getByRole('button', { name: 'Next', exact: true }).click(); await ready();
  check(await page.locator('.notification').count() > 0 && await page.locator('.notification').count() < 50, 'Last page contains remaining records');
  await page.getByRole('button', { name: 'Other human', exact: true }).click(); await ready();
  check(await parameter('page') === null, 'History filter resets page');
  const before = await page.evaluate(async () => (await (await fetch('/api/notification-history')).json()).total);
  await page.locator('.notification > summary').first().click();
  await page.getByRole('button', { name: 'Resend', exact: true }).first().click(); await ready();
  const after = await page.evaluate(async () => (await (await fetch('/api/notification-history')).json()).total);
  check(before === after, 'Resend retains the history record count');
  await page.route('**/api/notification-records/*/resend', route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":"Synthetic resend failure"}' }));
  await page.locator('.notification > summary').first().click();
  await page.getByRole('button', { name: 'Resend', exact: true }).first().click();
  await page.getByText('Synthetic resend failure', { exact: true }).waitFor(); check(true, 'Resend failures are visible');
  await page.unroute('**/api/notification-records/*/resend');
  await go('/notification-history?repo=missing/repo');
  check(await page.getByText('No notifications match these filters.', { exact: true }).isVisible(), 'Empty history has an explicit state');
  check(await page.getByRole('button', { name: 'Refresh', exact: true }).count() === 0, 'History has no refresh action');
  await page.route('**/api/me', route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":"Synthetic identity failure"}' }));
  await page.getByRole('link', { name: 'Logs', exact: true }).click();
  await page.getByText('Synthetic identity failure', { exact: true }).waitFor();
  check(await page.locator('#identity').textContent() === 'Identity unavailable', 'Identity failure is explicit');
  await page.unroute('**/api/me'); await page.getByRole('button', { name: 'Retry', exact: true }).click(); await ready();
  check(await page.locator('#identity > span').last().textContent() === '@alex', 'Identity failure can recover');

  await go('/?tab=needs-my-review');
  await page.getByRole('button', { name: '＋ Track PR', exact: true }).click();
  await page.getByLabel('GitHub pull request URL', { exact: true }).fill('https://github.com/denied/repo/pull/7');
  await page.getByRole('button', { name: 'Track pull request', exact: true }).click();
  await page.getByText('Unable to track pull request; check URL and GitHub access', { exact: true }).waitFor();
  check(await page.locator('#track-dialog').isVisible(), 'Failed tracking leaves dialog open');
  await page.getByLabel('GitHub pull request URL', { exact: true }).fill('https://github.com/acme/widget/pull/100');
  await page.getByRole('button', { name: 'Track pull request', exact: true }).click();
  await page.locator('#track-dialog').waitFor({ state: 'hidden' }); await ready();
  check(await parameter('tab') === 'needs-my-review', 'Tracking preserves queue');
  check(await page.getByText('Manually tracked synthetic PR', { exact: true }).count() === 0, 'Hidden tracked item does not rewrite filters');
  await page.getByRole('button', { name: /^My PRs/ }).click(); await ready();
  const manual = page.locator('.pr').filter({ hasText: 'Manually tracked synthetic PR' });
  await manual.locator('summary').click(); await manual.getByRole('button', { name: 'Untrack', exact: true }).click(); await ready();
  check(await page.getByText('Manually tracked synthetic PR', { exact: true }).count() === 0, 'Untrack updates current results');
  await page.getByRole('button', { name: 'Inactive', exact: true }).click(); await ready();
  const inactive = page.locator('.pr').filter({ hasText: 'Manually tracked synthetic PR' });
  if (await inactive.getAttribute('open') === null) await inactive.locator('summary').click();
  await inactive.getByRole('button', { name: 'Retrack', exact: true }).click(); await ready();
  check(await page.getByText('Manually tracked synthetic PR', { exact: true }).isVisible(), 'Retrack succeeds');
  await page.getByRole('button', { name: '＋ Track PR', exact: true }).click();
  await page.getByLabel('GitHub pull request URL', { exact: true }).fill('https://github.com/acme/widget/pull/101');
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: 'Logs', exact: true }).click(); await ready();
  check(await page.locator('#track-dialog').isHidden(), 'Navigation resets tracking dialog');
  await page.getByRole('combobox', { name: 'Log level', exact: true }).selectOption('warn'); await ready();
  check(await page.locator('.log').count() === 1, 'Logs use exact severity filter');
  await page.getByText('Context', { exact: true }).click();
  check(await page.locator('.log pre').isVisible(), 'Structured log context expands');

  await go('/');
  await page.evaluate(() => { window.originalFetch = window.fetch; window.fetch = (input, init) => window.originalFetch(input, { ...init, signal: undefined }); });
  let requestNumber = 0; let release; let observed;
  const firstSeen = new Promise(resolve => { observed = resolve; });
  const held = new Promise(resolve => { release = resolve; });
  await page.route('**/api/pull-request-timeline*', async route => {
    const number = ++requestNumber;
    const response = await route.fetch(); const data = await response.json();
    data.items.find(pr => pr.id === 'A').snapshot.title = number === 1 ? 'Stale response' : 'Latest response';
    if (number === 1) { observed(); await held; }
    await route.fulfill({ response, json: data });
  });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click(); await firstSeen;
  await page.getByRole('button', { name: 'Merged', exact: true }).click();
  await page.getByText('Latest response', { exact: true }).waitFor();
  const staleResponse = page.waitForResponse(response => response.url().includes('/api/pull-request-timeline'));
  release(); await staleResponse;
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  check(await page.getByText('Stale response', { exact: true }).count() === 0, 'Stale successful response cannot replace latest state when cancellation is ignored');
  await page.unroute('**/api/pull-request-timeline*');
  await page.evaluate(() => { window.fetch = window.originalFetch; delete window.originalFetch; });

  await go('/');
  let releaseFilter; let filterSeen;
  const waitingFilter = new Promise(resolve => { filterSeen = resolve; });
  const filterGate = new Promise(resolve => { releaseFilter = resolve; });
  let filterCalls = 0;
  await page.route('**/api/pull-request-timeline*', async route => {
    const response = await route.fetch();
    if (++filterCalls === 1) { filterSeen(); await filterGate; }
    try { await route.fulfill({ response }); } catch {}
  });
  await page.getByRole('button', { name: 'Inactive', exact: true }).click(); await waitingFilter;
  await page.getByRole('button', { name: 'Merged', exact: true }).click(); await ready();
  const selected = await parameter('pr-state', true);
  check(selected.includes('inactive') && selected.includes('merged'), 'Rapid independent filter selections accumulate');
  releaseFilter(); await page.unroute('**/api/pull-request-timeline*');

  await page.route('**/api/pull-request-timeline*', async route => {
    const response = await route.fetch(); const data = await response.json();
    data.items.find(pr => pr.id === 'A').snapshot.title = '<img src=x onerror="window.compromised=true">';
    await route.fulfill({ response, json: data });
  });
  await go('/');
  check(await page.getByText('<img src=x onerror="window.compromised=true">', { exact: true }).isVisible(), 'External titles render as text');
  check(await page.evaluate(() => !window.compromised && !document.querySelector('img[src=x]')), 'External markup cannot execute');
  await page.unroute('**/api/pull-request-timeline*');
  await page.setViewportSize({ width: 360, height: 800 }); await go('/');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout has no horizontal page overflow');
  await capture('navigation-mobile.png');
  await page.setViewportSize({ width: 1280, height: 900 }); await go('/');
  await page.getByRole('link', { name: 'Logs', exact: true }).click(); await ready();
  await page.getByRole('link', { name: 'Pull Requests', exact: true }).click(); await ready();
  await page.getByRole('button', { name: '＋ Track PR', exact: true }).click();
  await page.getByLabel('GitHub pull request URL', { exact: true }).fill('https://github.com/acme/widget/pull/102');
  await page.goBack(); await ready();
  check(await page.locator('#track-dialog').isHidden(), 'Back navigation dismisses an open tracking dialog');
  await page.goForward(); await ready();
  await page.getByRole('button', { name: '＋ Track PR', exact: true }).click();
  check(await page.getByLabel('GitHub pull request URL', { exact: true }).inputValue() === '', 'Navigation clears the tracking URL');
  await page.keyboard.press('Escape');
  check(errors.length === 0, `No browser runtime errors: ${errors.join('; ')}`);
  return { checks, status: 'pass' };
}
