import { execFile } from 'node:child_process';
import { lstat, readFile, rm, unlink } from 'node:fs/promises';
import { homedir } from 'node:os';
import { isAbsolute, join } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import Database from 'better-sqlite3';

const execute = promisify(execFile);
const marker = '# Generated by Octopulse replacement';

export async function uninstallUserService(home, { run = execute, confirmDataRemoval = async () => false } = {}) {
  if (typeof home !== 'string' || !isAbsolute(home) || /[\r\n\0]/.test(home)) throw new Error('Absolute single-line home path is required');
  const unit = join(home, '.config/systemd/user/octopulse.service');
  const launcher = join(home, '.local/bin/octopulse');
  const identity = join(home, '.local/share/applications/octopulse.desktop');
  const dataDirectories = [join(home, '.config/octopulse'), join(home, '.local/state/octopulse')];
  const managed = [];
  for (const path of [unit, launcher, identity]) {
    try {
      if (!(await lstat(path)).isFile()) throw new Error(`Refusing to remove an unmanaged file: ${path}`);
      const text = await readFile(path, 'utf8');
      if (!text.startsWith(`${marker}\n`) && !(path === launcher && text.startsWith(`#!/bin/sh\n${marker}\n`))) {
        throw new Error(`Refusing to remove an unmanaged file: ${path}`);
      }
      managed.push(path);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  if (managed.includes(unit)) await run('systemctl', ['--user', 'disable', '--now', 'octopulse.service']);
  const removed = [];
  for (const path of managed) {
    await unlink(path);
    removed.push(path);
  }
  if (managed.includes(unit)) await run('systemctl', ['--user', 'daemon-reload']);
  const existingData = [];
  for (const path of dataDirectories) {
    try { await lstat(path); existingData.push(path); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  let dataRemoved = false;
  if (existingData.length && await confirmDataRemoval(dataDirectories) === true) {
    let ownership;
    try {
      const lock = join(home, '.local/state/octopulse/ownership.sqlite');
      try {
        await lstat(lock);
        ownership = new Database(lock, { fileMustExist: true, timeout: 0 });
        ownership.exec('BEGIN EXCLUSIVE');
      } catch (error) {
        if (error.code !== 'ENOENT') throw new Error('Cannot exclusively access Octopulse data; stop any running Octopulse process before deleting it', { cause: error });
      }
      for (const path of existingData) {
        await rm(path, { recursive: true, force: true });
        removed.push(path);
      }
      dataRemoved = true;
    } finally { ownership?.close(); }
  }
  return { removed, dataRemoved };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv.length !== 2) throw new Error('Usage: npm run user-service:uninstall');
    const result = await uninstallUserService(homedir(), {
      confirmDataRemoval: async directories => {
        if (!process.stdin.isTTY || !process.stdout.isTTY) return false;
        const prompt = createInterface({ input: process.stdin, output: process.stdout });
        try { return /^(y|yes)$/i.test((await prompt.question(`Delete all Octopulse data, including config, database, history, logs, caches, and these directories?\n${directories.join('\n')}\nThis cannot be undone. [y/N] `)).trim()); }
        finally { prompt.close(); }
      },
    });
    console.log(`Removed ${result.removed.length} files or directories.`);
    console.log(result.dataRemoved ? 'All Octopulse data directories removed.' : 'Octopulse config and data kept (if present).');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
