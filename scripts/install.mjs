import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { isAbsolute, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs, promisify } from 'node:util';
import { execFile } from 'node:child_process';

const execute = promisify(execFile);
const marker = '# Generated by Octopulse replacement';
const unitQuote = value => `"${value.replaceAll('%', '%%').replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('$', () => '$$')}"`;
const shellQuote = value => `'${value.replaceAll("'", "'\\''")}'`;

export async function installPackage(bundle, home, { activate = false, instance = 'octopulse', port = 3000 } = {}, service = args => execute('systemctl', args)) {
  if (!isAbsolute(bundle) || !isAbsolute(home) || /[\r\n\0]/.test(home + bundle)) throw new Error('Absolute single-line package and home paths are required');
  if (typeof instance !== 'string' || !/^[a-z][a-z0-9-]{0,63}$/.test(instance)) throw new Error('Invalid instance name');
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('Port must be between 1 and 65535');
  const manifest = JSON.parse(await readFile(join(bundle, 'octopulse-package.json'), 'utf8'));
  if (manifest.schema !== 1 || manifest.target !== 'linux-x64-glibc' || !/^[a-f0-9]{64}$/.test(manifest.digest)) throw new Error('Invalid Octopulse package manifest');
  const prefix = join(home, '.local/lib/octopulse', manifest.digest);
  const profile = join(home, '.local/state', instance);
  const unit = join(home, '.config/systemd/user', `${instance}.service`);
  const launcher = join(home, '.local/bin', instance);
  const identity = join(home, '.local/share/applications', `${instance}.desktop`);
  for (const path of [unit, launcher, identity]) {
    try { if (!(await readFile(path, 'utf8')).includes(marker)) throw new Error('Existing Octopulse installation requires an approved coexistence procedure'); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  try {
    const installed = JSON.parse(await readFile(join(prefix, 'octopulse-package.json'), 'utf8'));
    if (installed.digest !== manifest.digest) throw new Error('Package destination is already occupied');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await mkdir(join(home, '.local/lib/octopulse'), { recursive: true, mode: 0o700 });
    await cp(bundle, prefix, { recursive: true, errorOnExist: true, force: false });
  }
  for (const directory of ['.config/systemd/user', '.local/bin', '.local/share/applications']) {
    await mkdir(join(home, directory), { recursive: true, mode: 0o700 });
  }
  const node = join(prefix, 'runtime/bin/node');
  const daemon = join(prefix, 'dist/src/daemon.js');
  const args = [node, daemon, '--instance', instance, '--port', String(port), '--profile', profile];
  const title = instance === 'octopulse' ? 'Octopulse' : `Octopulse (${instance})`;
  await writeFile(unit, `${marker}\n[Unit]\nDescription=${title} GitHub pull request monitor\nAfter=network-online.target graphical-session.target\nPartOf=graphical-session.target\n\n[Service]\nType=simple\nExecStart=${args.map(unitQuote).join(' ')}\nRestart=on-failure\nRestartSec=5\nUMask=0077\n\n[Install]\nWantedBy=graphical-session.target\n`, { mode: 0o600 });
  await writeFile(launcher, `#!/bin/sh\n${marker}\nexec ${args.map(shellQuote).join(' ')} "$@"\n`, { mode: 0o700 });
  await writeFile(identity, `${marker}\n[Desktop Entry]\nType=Application\nName=${title}\nComment=GitHub pull request monitor\nNoDisplay=true\nExec=xdg-open http://127.0.0.1:${port}\nIcon=${join(prefix, 'assets/octopulse-mark-small-white.svg')}\nX-GNOME-UsesNotifications=true\n`, { mode: 0o600 });
  if (activate) { await service(['--user', 'daemon-reload']); await service(['--user', 'enable', `${instance}.service`]); }
  return { prefix, profile, unit, launcher, identity, instance, port };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { values } = parseArgs({ options: { home: { type: 'string' }, activate: { type: 'boolean' }, instance: { type: 'string' },
      port: { type: 'string' } }, strict: true });
    if (!values.home) throw new Error('Usage: install.mjs --home /absolute/home [--instance name] [--port port] [--activate]');
    if (values.port !== undefined && !/^\d+$/.test(values.port)) throw new Error('Invalid port');
    const result = await installPackage(fileURLToPath(new URL('../', import.meta.url)), values.home, {
      activate: values.activate, instance: values.instance, port: values.port === undefined ? undefined : Number(values.port),
    });
    console.log(`Installed ${result.instance}. Start ${result.instance}.service, then configure Settings at http://127.0.0.1:${result.port}.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
